/// Convenience used by tests to scaffold into a temp root.
pub async fn scaffold_into(
    root: &std::path::Path,
    kind: Kind,
    name: &str,
    force: bool,
) -> CliResult<Vec<Generated>> {
    generators::generate(
        kind,
        root,
        &MakeOptions {
            name: name.to_string(),
            force,
            resource: false,
            with_migration: false,
        },
    )
}
